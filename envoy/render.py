#!/usr/bin/env python3
"""Generate Envoy configs for each Assignment 3 load-balancing policy.

    python3 envoy/render.py        # writes envoy/envoy-<policy>.yaml for all policies

docker-compose.yml mounts the file named by ENVOY_CONFIG (default round robin):
    ENVOY_CONFIG=envoy-a-only.yaml docker compose up -d envoy
"""
from pathlib import Path

REPLICAS = {"A": "homeshop-app-1", "B": "homeshop-app-2", "C": "homeshop-app-3"}

POLICIES = {
    # name: (lb_policy, {replica: weight})
    "a-only": ("ROUND_ROBIN", {"A": 1}),
    "round-robin": ("ROUND_ROBIN", {"A": 1, "B": 1, "C": 1}),
    "weighted": ("ROUND_ROBIN", {"A": 2, "B": 1, "C": 1}),
    "least-request": ("LEAST_REQUEST", {"A": 1, "B": 1, "C": 1}),
}

# Active health checks (recorded in the report): probe every 2 s, 1 s timeout,
# 2 failures -> unhealthy, 2 successes -> healthy again.
HEALTH = """\
    health_checks:
    - timeout: 1s
      interval: 2s
      no_traffic_interval: 2s
      unhealthy_threshold: 2
      healthy_threshold: 2
{check}"""

ACCESS_LOG = """\
          access_log:
          - name: envoy.access_loggers.stdout
            typed_config:
              "@type": type.googleapis.com/envoy.extensions.access_loggers.stream.v3.StdoutAccessLog
              log_format:
                json_format:
                  service: homeshop-envoy
                  message: envoy_access
                  listener: {interface}
                  start_time: "%START_TIME%"
                  request_id: "%REQ(X-REQUEST-ID)%"
                  method: "%REQ(:METHOD)%"
                  path: "%REQ(:PATH)%"
                  response_code: "%RESPONSE_CODE%"
                  grpc_status: "%GRPC_STATUS%"
                  response_flags: "%RESPONSE_FLAGS%"
                  duration_ms: "%DURATION%"
                  upstream_host: "%UPSTREAM_HOST%"
                  replica: "%RESP(X-REPLICA)%"
"""


def listener(name, port, codec, cluster, interface):
    return f"""\
  - name: {name}
    address:
      socket_address: {{ address: 0.0.0.0, port_value: {port} }}
    filter_chains:
    - filters:
      - name: envoy.filters.network.http_connection_manager
        typed_config:
          "@type": type.googleapis.com/envoy.extensions.filters.network.http_connection_manager.v3.HttpConnectionManager
          stat_prefix: {name}
          codec_type: {codec}
          generate_request_id: true
          route_config:
            virtual_hosts:
            - name: {name}
              domains: ["*"]
              routes:
              - match: {{ prefix: "/" }}
                route: {{ cluster: {cluster}, timeout: 10s }}
          http_filters:
          - name: envoy.filters.http.router
            typed_config:
              "@type": type.googleapis.com/envoy.extensions.filters.http.router.v3.Router
{ACCESS_LOG.format(interface=interface)}"""


def cluster(name, port, lb_policy, weights, check, http2):
    endpoints = "".join(
        f"""\
        - endpoint:
            hostname: {REPLICAS[r]}
            address:
              socket_address: {{ address: {REPLICAS[r]}, port_value: {port} }}
          load_balancing_weight: {w}
"""
        for r, w in weights.items()
    )
    proto = (
        """\
    typed_extension_protocol_options:
      envoy.extensions.upstreams.http.v3.HttpProtocolOptions:
        "@type": type.googleapis.com/envoy.extensions.upstreams.http.v3.HttpProtocolOptions
        explicit_http_config:
          http2_protocol_options: {}
"""
        if http2
        else ""
    )
    return f"""\
  - name: {name}
    type: STRICT_DNS
    dns_refresh_rate: 5s
    connect_timeout: 1s
    lb_policy: {lb_policy}
{proto}    load_assignment:
      cluster_name: {name}
      endpoints:
      - lb_endpoints:
{endpoints}{HEALTH.format(check=check)}"""


def render(policy):
    lb_policy, weights = POLICIES[policy]
    return (
        f"# GENERATED by envoy/render.py - policy: {policy}\n"
        "admin:\n"
        "  address:\n"
        "    socket_address: { address: 0.0.0.0, port_value: 9901 }\n"
        "static_resources:\n"
        "  listeners:\n"
        + listener("http_ingress", 8000, "AUTO", "app_http", "http")
        # gRPC listener is HTTP/2 (not TCP proxy) so Envoy routes each call, not each connection.
        + listener("grpc_ingress", 50051, "HTTP2", "app_grpc", "grpc")
        + "  clusters:\n"
        + cluster("app_http", 8000, lb_policy, weights, "      http_health_check: { path: /healthz }\n", False)
        + cluster("app_grpc", 50051, lb_policy, weights, "      grpc_health_check: {}\n", True)
    )


if __name__ == "__main__":
    here = Path(__file__).parent
    for policy in POLICIES:
        (here / f"envoy-{policy}.yaml").write_text(render(policy))
        print(f"wrote envoy/envoy-{policy}.yaml")
